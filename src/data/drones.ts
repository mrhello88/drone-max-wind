export const brands = [...new Set(drones.map((d) => d.brand))];

export function droneBySlug(slug: string) {
	return drones.find((d) => d.slug === slug);
}

export function calculatorPath(drone: Drone) {
	return `/${drone.slug}-wind-resistance-calculator`;
}

export function groupedDrones() {
	const map = new Map<string, Drone[]>();
	for (const drone of drones) {
		const list = map.get(drone.brand) ?? [];
		list.push(drone);
		map.set(drone.brand, list);
	}
	return [...map.entries()];
}
